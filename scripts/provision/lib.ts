export class ProvisionError extends Error {}

export function fail(message: string): never {
  throw new ProvisionError(message)
}

/** Print the run summary and exit: 0 done, 2 waiting on a human, 1 failed. */
export function finish(name: string, error?: unknown): never {
  if (error) {
    console.error(`\n✗ ${name} stopped: ${error instanceof Error ? error.message : String(error)}`)
  }
  console.log(`\n── ${name} summary${dryRun ? ' (dry run: nothing was changed)' : ''}`)
  console.log(`   done ${report.done.length} · already done ${report.skipped.length} · planned ${report.planned.length}`)
  for (const w of report.warnings) console.log(`   ⚠ ${w}`)
  if (report.waiting.length) {
    console.log('\n   Waiting on a human. Do these, then run the same command again:')
    report.waiting.forEach((w, i) => console.log(`   ${i + 1}. ${w}`))
  }
  process.exit(error ? 1 : report.waiting.length ? 2 : 0)
}

// ─── .env.local ────────────────────────────────────────────────────────────────────

let values: Map<string, string> | null = null

function load() {
  if (!values) values = existsSync(ENV_FILE) ? parseDotenv(readFileSync(ENV_FILE, 'utf8')) : new Map()
  return values
}

export function getValue(key: string): string | undefined {
  const v = process.env[key] ?? load().get(key)
  return v === undefined || v.trim() === '' ? undefined : v.trim()
}

export function requireValue(key: string, hint: string): string {
  const v = getValue(key)
  if (!v) fail(`${key} is missing from ${ENV_FILE}. ${hint}`)
  return v
}

/** Store a generated value in .env.local (never in dry runs). Returns the value. */
export function saveValue(key: string, value: string) {
  load().set(key, value)
  if (dryRun) return value
  const text = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, 'utf8') : `# ${PRODUCT} provisioning secrets. Never commit this file.\n`
  const line = `${key}=${value}`
  const pattern = new RegExp(`^\\s*${key}\\s*=.*$`, 'm')
  let next: string
  if (pattern.test(text)) {
    next = text.replace(pattern, line)
  } else {
    const marker = '# ─── Generated by npm run provision (do not edit by hand) ───'
    next = text.includes(marker) ? `${text.replace(/\n?$/, '\n')}${line}\n` : `${text.replace(/\n?$/, '\n')}\n${marker}\n${line}\n`
  }
  writeFileSync(ENV_FILE, next, { mode: 0o600 })
  return value
}

/** A value from .env.local, generated and saved on first use. */
export function generatedValue(key: string, make: () => string) {
  return getValue(key) ?? saveValue(key, make())
}

