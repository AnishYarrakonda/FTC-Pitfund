// ─── HTTP ──────────────────────────────────────────────────────────────────────────────

export type Api = <T = unknown>(method: string, path: string, body?: unknown, opts?: { allow?: number[] }) => Promise<{ status: number; data: T }>

/** A small JSON client. Mutating calls are refused in dry runs (callers check `dryRun` first). */
export function apiClient(base: string, headers: Record<string, string>, label: string): Api {
  return async (method, path, body, opts) => {
    if (dryRun && method !== 'GET') throw new Error(`BUG: ${label} ${method} ${path} attempted during a dry run`)
    let res: Response
    try {
      res = await fetch(`${base}${path}`, {
        method,
        headers: { 'Content-Type': 'application/json', ...headers },
        body: body === undefined ? undefined : JSON.stringify(body),
        signal: AbortSignal.timeout(60_000),
      })
    } catch (e) {
      fail(`Couldn't reach ${label} (${method} ${path}): ${e instanceof Error ? e.message : e}`)
    }
    const text = await res.text()
    let data: unknown = text
    try {
      data = text ? JSON.parse(text) : null
    } catch {
      // keep text
    }
    if (!res.ok && !opts?.allow?.includes(res.status)) {
      const detail = typeof data === 'string' ? data.slice(0, 300) : JSON.stringify(data).slice(0, 300)
      fail(`${label} ${method} ${path} → ${res.status}: ${detail}`)
    }
    return { status: res.status, data: data as never }
  }
}

